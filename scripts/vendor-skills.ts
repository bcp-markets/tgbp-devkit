/**
 * Copies the skills the MCP server serves from a checkout of the private
 * agent-skills repo into src/mcp/skills.generated.ts, so the server ships
 * them byte for byte and the repo stays their one source.
 *
 *   TGBP_AGENT_SKILLS_DIR=<agent-skills checkout> pnpm generate:skills
 *
 * agent-skills.lock pins the commit the copy comes from. CI checks out exactly
 * that commit and test/skills-drift.test.ts fails when the copy differs, so
 * the pin moves only when someone copies again.
 */
import { execFileSync } from 'node:child_process'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const LOCK_PATH = fileURLToPath(new URL('../agent-skills.lock', import.meta.url))
export const OUTPUT_PATH = fileURLToPath(new URL('../src/mcp/skills.generated.ts', import.meta.url))

/** The skills the devkit server serves, by folder under the repo's skills/. */
export const SKILLS = ['tgbp-build-integration']

export function skillsCommit(skillsDir: string): string {
  return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: skillsDir, encoding: 'utf8' }).trim()
}

/** Every file in a folder, recursively, keyed by its `/`-separated path under `root`. */
function filesUnder(root: string, dir: string): [string, string][] {
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((entry): [string, string][] => {
      const path = join(dir, entry.name)
      if (entry.isDirectory()) return filesUnder(root, path)
      if (!entry.isFile()) throw new Error(`${path} is not a plain file`)
      return [[relative(root, path).split('\\').join('/'), readFileSync(path, 'utf8')]]
    })
    .sort(([a], [b]) => (a < b ? -1 : 1))
}

/** Renders the generated module from a checkout. The CI disclosure sweep covers its output. */
export function renderSkillsModule(skillsDir: string): string {
  const root = join(skillsDir, 'skills')
  const files = Object.fromEntries(SKILLS.flatMap((skill) => filesUnder(root, join(root, skill))))
  return [
    '// GENERATED by scripts/vendor-skills.ts from the agent-skills repo. Do not edit.',
    '// Regenerate: TGBP_AGENT_SKILLS_DIR=<checkout> pnpm generate:skills (see the script)',
    '',
    '/** Each served skill file, keyed by its path: `<skill>/SKILL.md`. */',
    `export const SKILL_FILES: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 2)}`,
    '',
  ].join('\n')
}

function main(): void {
  const skillsDir = process.env.TGBP_AGENT_SKILLS_DIR
  if (!skillsDir) {
    console.error('Set TGBP_AGENT_SKILLS_DIR to a checkout of the private agent-skills repo')
    process.exit(2)
  }
  const dir = resolve(skillsDir)
  // agent-skills.lock pins a commit, so a copy of uncommitted edits would claim a source it lacks.
  const status = execFileSync('git', ['status', '--porcelain'], { cwd: dir, encoding: 'utf8' })
  if (status.trim() !== '') {
    console.error(`${skillsDir} has uncommitted changes; commit or discard them, then copy again`)
    process.exit(1)
  }
  const commit = skillsCommit(dir)
  writeFileSync(OUTPUT_PATH, renderSkillsModule(dir))
  writeFileSync(LOCK_PATH, `${commit}\n`)
  console.log(`Copied ${SKILLS.join(', ')} from agent-skills commit ${commit}`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
